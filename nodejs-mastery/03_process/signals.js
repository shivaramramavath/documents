/*
 * ============================================================
 * 23. Windows note
 * ============================================================
 *
 * Signal behavior differs between Windows and Unix-like
 * operating systems.
 *
 * In particular, not every POSIX signal has identical semantics
 * on Windows.
 *
 *
 * For Node.js backend development, focus especially on:
 *
 *
 *     SIGINT
 *     SIGTERM
 *
 *
 * and test the actual deployment environment your application
 * will run in.
 *
 * ============================================================
 */

/*
 * ============================================================
 * 24. Process events are different from signals
 * ============================================================
 *
 *
 * Process event:
 *
 *
 *     process.on("exit", ...)
 *
 *
 * is a Node.js lifecycle event.
 *
 *
 * Signal:
 *
 *
 *     process.on("SIGTERM", ...)
 *
 *
 * represents an operating-system process signal.
 *
 *
 * They are related to process lifecycle but are NOT the same
 * thing.
 *
 * ============================================================
 */

/*
 * ============================================================
 * 25. Common signals
 * ============================================================
 *
 *
 * SIGINT
 *
 *     Interrupt.
 *
 *     Commonly Ctrl+C.
 *
 *
 * SIGTERM
 *
 *     Termination request.
 *
 *     Common graceful-shutdown signal.
 *
 *
 * SIGKILL
 *
 *     Immediate process termination on supported platforms.
 *
 *     Cannot be handled by the application.
 *
 *
 * SIGSTOP
 *
 *     Stops a process on supported platforms.
 *
 *
 * ============================================================
 */

/*
 * ============================================================
 * 26. SIGKILL
 * ============================================================
 *
 * SIGKILL is important to understand.
 *
 *
 * The application cannot catch SIGKILL and perform cleanup.
 *
 *
 * Therefore:
 *
 *
 *     SIGTERM
 *         ↓
 *     graceful cleanup
 *
 *
 * is fundamentally different from:
 *
 *
 *     SIGKILL
 *         ↓
 *     immediate termination
 *
 * ============================================================
 */

/*
 * ============================================================
 * 27. Real production shutdown
 * ============================================================
 *
 * A realistic backend might have:
 *
 *
 *     async function shutdown(signal) {
 *
 *       if (isShuttingDown) {
 *         return;
 *       }
 *
 *       isShuttingDown = true;
 *
 *       console.log(
 *         `${signal} received`,
 *       );
 *
 *       await closeHttpServer();
 *
 *       await closeMongoDB();
 *
 *       await closeRedis();
 *
 *       await closeKafka();
 *
 *       process.exitCode = 0;
 *
 *     }
 *
 *
 * This is a simplified conceptual example.
 *
 * ============================================================
 */

