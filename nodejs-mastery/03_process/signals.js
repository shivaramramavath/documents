/*
 * ============================================================
 * 29. Common mistakes
 * ============================================================
 *
 *
 * ❌ Mistake 1:
 *
 *     Calling process.exit() immediately.
 *
 *
 * ❌ Mistake 2:
 *
 *     Having duplicate shutdown logic.
 *
 *
 * ❌ Mistake 3:
 *
 *     Closing resources multiple times.
 *
 *
 * ❌ Mistake 4:
 *
 *     Waiting forever for cleanup.
 *
 *
 * ❌ Mistake 5:
 *
 *     Assuming every signal behaves identically on every OS.
 *
 *
 * ❌ Mistake 6:
 *
 *     Ignoring SIGTERM in production server applications.
 *
 * ============================================================
 */

/*
 * ============================================================
 * 30. Best-practice checklist
 * ============================================================
 *
 *
 *     ✓ Handle SIGTERM.
 *
 *     ✓ Handle SIGINT for local development.
 *
 *     ✓ Centralize shutdown logic.
 *
 *     ✓ Make shutdown idempotent.
 *
 *     ✓ Stop accepting new work.
 *
 *     ✓ Close resources.
 *
 *     ✓ Set appropriate exit code.
 *
 *     ✓ Have a shutdown timeout.
 *
 *     ✓ Avoid unnecessary process.exit().
 *
 * ============================================================
 */

/*
 * ============================================================
 * FINAL CHEAT SHEET
 * ============================================================
 *
 *
 * Listen for Ctrl+C:
 *
 *     process.on(
 *       "SIGINT",
 *       handler,
 *     );
 *
 *
 * Listen for termination:
 *
 *     process.on(
 *       "SIGTERM",
 *       handler,
 *     );
 *
 *
 * Set exit status:
 *
 *     process.exitCode = 0;
 *
 *
 * Force termination:
 *
 *     process.exit(1);
 *
 *
 * Prevent duplicate shutdown:
 *
 *     let isShuttingDown = false;
 *
 *
 * ============================================================
 *
 * KEY IDEA:
 *
 *     Signals allow a Node.js application to respond to
 *     operating-system requests such as interruption and
 *     termination.
 *
 *
 *     SIGINT  -> usually Ctrl+C
 *     SIGTERM -> graceful termination request
 *
 *
 * Production Node.js servers should use these signals to
 * implement graceful shutdown.
 *
 * ============================================================
 */
